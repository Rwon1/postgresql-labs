 GROUP BY o.order_id,o.customer_id,o.order_date
), customer_stats AS (
 SELECT customer_id,COUNT(*) AS orders_count,SUM(total) AS revenue,
        AVG(total) AS avg_order,MAX(order_date) AS last_order
